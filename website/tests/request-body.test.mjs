import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const context={exports:{},TextDecoder,Uint8Array,Response,SyntaxError};
vm.runInNewContext(ts.transpileModule(readFileSync('lib/request-body.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
export const {readLimitedBytes,readLimitedText,bodyErrorResponse}=context.exports;
const request=(body,headers={})=>new Request('https://test/api',{method:'POST',body,headers,...(body instanceof ReadableStream?{duplex:'half'}:{})});
assert.equal(await readLimitedText(request('abcd'),4),'abcd');
assert.equal(await readLimitedText(request('é'),2),'é');
await assert.rejects(()=>readLimitedText(request('é'),1),e=>e.status===413);
await assert.rejects(()=>readLimitedText(request('abcd',{'content-length':'9999'}),4),e=>e.status===413);
let cancelled=false;
const stream=new ReadableStream({pull(c){c.enqueue(new Uint8Array(3))},cancel(){cancelled=true}});
await assert.rejects(()=>readLimitedBytes(request(stream),5),e=>e.status===413);assert.equal(cancelled,true);
assert.equal(bodyErrorResponse(new SyntaxError('private data')).status,400);
assert.equal((await bodyErrorResponse(new SyntaxError('private data')).json()).error,'Format data tidak valid.');
assert.equal(bodyErrorResponse(new Error('server issue')),null);
console.log('PASS: byte limits, UTF-8, chunked-body cancellation, safe malformed-JSON errors');
